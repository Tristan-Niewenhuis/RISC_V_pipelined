#!/usr/bin/env python3
"""Create fixed-depth 32-bit little-endian Vivado COE images from an ELF32 file.

The first COE vector entry maps to the lowest address in the selected memory.
Allocated sections are placed by their ELF virtual addresses. SHT_NOBITS (.bss)
remains zero-filled. No third-party Python packages are required.
"""

from __future__ import annotations

import argparse
import struct
import sys
from pathlib import Path

ELFCLASS32 = 1
ELFDATA2LSB = 1
EM_RISCV = 243
SHF_ALLOC = 0x2
SHT_NOBITS = 8


def parse_int(value: str) -> int:
    return int(value, 0)


def read_elf_sections(path: Path) -> list[dict[str, int | str | bytes]]:
    data = path.read_bytes()
    if len(data) < 52 or data[:4] != b"\x7fELF":
        raise ValueError(f"{path}: not an ELF file")
    if data[4] != ELFCLASS32:
        raise ValueError(f"{path}: expected ELF32 (your target is RV32)")
    if data[5] != ELFDATA2LSB:
        raise ValueError(f"{path}: expected little-endian ELF")

    header = struct.unpack_from("<16sHHIIIIIHHHHHH", data, 0)
    machine = header[2]
    shoff = header[6]
    shentsize = header[11]
    shnum = header[12]
    shstrndx = header[13]
    if machine != EM_RISCV:
        raise ValueError(f"{path}: ELF machine field is {machine}, not RISC-V")
    if shentsize < 40 or shoff + shentsize * shnum > len(data):
        raise ValueError(f"{path}: invalid section-header table")
    if shstrndx >= shnum:
        raise ValueError(f"{path}: invalid section-name string-table index")

    raw_headers = [
        struct.unpack_from("<IIIIIIIIII", data, shoff + i * shentsize)
        for i in range(shnum)
    ]
    string_header = raw_headers[shstrndx]
    str_off, str_size = string_header[4], string_header[5]
    if str_off + str_size > len(data):
        raise ValueError(f"{path}: invalid section-name string table")
    strings = data[str_off : str_off + str_size]

    sections: list[dict[str, int | str | bytes]] = []
    for index, sh in enumerate(raw_headers):
        name_off, section_type, flags, addr, offset, size = sh[:6]
        if name_off >= len(strings):
            name = f"<section-{index}>"
        else:
            end = strings.find(b"\0", name_off)
            if end < 0:
                end = len(strings)
            name = strings[name_off:end].decode("ascii", errors="replace")
        if section_type != SHT_NOBITS and offset + size > len(data):
            raise ValueError(f"{path}: section {name!r} extends past end of file")
        content = b"" if section_type == SHT_NOBITS else data[offset : offset + size]
        sections.append(
            {
                "name": name,
                "type": section_type,
                "flags": flags,
                "addr": addr,
                "size": size,
                "content": content,
            }
        )
    return sections


def make_memory(
    sections: list[dict[str, int | str | bytes]], base: int, size: int, label: str
) -> tuple[bytearray, list[str]]:
    if size <= 0 or size % 4:
        raise ValueError(f"{label}: memory size must be a positive multiple of four")
    mem = bytearray(size)
    occupied = bytearray(size)
    placed: list[str] = []
    for section in sections:
        flags = int(section["flags"])
        sec_size = int(section["size"])
        if not (flags & SHF_ALLOC) or sec_size == 0:
            continue
        addr = int(section["addr"])
        name = str(section["name"])
        sec_end = addr + sec_size
        mem_end = base + size
        if addr >= base and sec_end <= mem_end:
            start = addr - base
        elif sec_end <= base or addr >= mem_end:
            continue  # Allocated section belongs to the other memory region.
        else:
            raise ValueError(
                f"section {name!r} at [0x{addr:08x},0x{sec_end:08x}) crosses "
                f"the {label} boundary [0x{base:08x},0x{mem_end:08x})"
            )
        content = bytes(section["content"])
        if content:
            if len(content) != sec_size:
                raise ValueError(f"section {name!r}: file content length mismatch")
            if any(occupied[start : start + sec_size]):
                raise ValueError(f"section {name!r} overlaps another allocated section in {label}")
            mem[start : start + sec_size] = content
            occupied[start : start + sec_size] = b"\x01" * sec_size
        # SHT_NOBITS (.bss) intentionally retains the zero fill.
        placed.append(f"{name}@0x{addr:08x}+0x{sec_size:x}")
    return mem, placed


def write_coe(path: Path, memory: bytearray) -> None:
    if len(memory) % 4:
        raise ValueError("internal error: memory size is not word-aligned")
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="ascii", newline="\n") as output:
        output.write("; Generated by tools/elf_to_coe.py: one 32-bit word per vector entry\n")
        output.write("; First entry is the lowest address; words use RISC-V little-endian byte order.\n")
        output.write("memory_initialization_radix=16;\n")
        output.write("memory_initialization_vector=\n")
        words = len(memory) // 4
        for i in range(words):
            word = int.from_bytes(memory[4 * i : 4 * i + 4], "little")
            output.write(f"{word:08x}{';' if i == words - 1 else ','}\n")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("elf", type=Path, help="input RV32 ELF file")
    parser.add_argument("--rom", type=Path, required=True, help="output ROM COE path")
    parser.add_argument("--ram", type=Path, required=True, help="output RAM COE path")
    parser.add_argument("--rom-base", type=parse_int, default=0x00000000)
    parser.add_argument("--rom-bytes", type=parse_int, default=0x00010000)
    parser.add_argument("--ram-base", type=parse_int, default=0x00010000)
    parser.add_argument("--ram-bytes", type=parse_int, default=0x00010000)
    args = parser.parse_args()

    try:
        sections = read_elf_sections(args.elf)
        rom, rom_sections = make_memory(sections, args.rom_base, args.rom_bytes, "ROM")
        ram, ram_sections = make_memory(sections, args.ram_base, args.ram_bytes, "RAM")
        write_coe(args.rom, rom)
        write_coe(args.ram, ram)
    except (OSError, ValueError, struct.error) as exc:
        print(f"elf_to_coe.py: error: {exc}", file=sys.stderr)
        return 2

    print(f"ROM: {args.rom} ({args.rom_bytes // 4} x 32-bit words; base 0x{args.rom_base:08x})")
    print("  sections: " + (", ".join(rom_sections) if rom_sections else "none; all zero-filled"))
    print(f"RAM: {args.ram} ({args.ram_bytes // 4} x 32-bit words; base 0x{args.ram_base:08x})")
    print("  sections: " + (", ".join(ram_sections) if ram_sections else "none; all zero-filled"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
